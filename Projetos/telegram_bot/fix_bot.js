const fs = require('fs');
let code = fs.readFileSync('Projetos/telegram_bot/bot.js', 'utf8');
code = code.replace(/\^\\\\\/start\$/g, '^\\/start$');
code = code.replace(/\^\\\\\/tarefas\$/g, '^\\/tarefas$');
code = code.replace(/\^\\\\\/noticias\$/g, '^\\/noticias$');
code = code.replace(/\^\\\\\/status\$/g, '^\\/status$');
code = code.replace(/\^\\\\\/nota/g, '^\\/nota');
code = code.replace(/\\\\n/g, '\\n');
fs.writeFileSync('Projetos/telegram_bot/bot.js', code);
console.log('Fixed regex syntax');
